import sys
import re
import struct

sys.path.append('tools')
from rdwr_phy62x2 import phyflasher, ParseHexFile

phy = object.__new__(phyflasher)
phy.tg7100 = False
hp = ParseHexFile('firmware/build/custom_firmware.hex')
hdr_wire = phyflasher.HexfHeader(phy, hp)

print(f"Wire header total generated bytes: {len(hdr_wire)}")

with open('firmware/src/wire_boot_header.h', 'r') as f:
    content = f.read()

hex_matches = re.findall(r'0x([0-9A-Fa-f]{2})', content)
header_h_bytes = bytes([int(x, 16) for x in hex_matches])

print(f"wire_boot_header.h bytes count: {len(header_h_bytes)}")

if bytes(hdr_wire[:320]) == header_h_bytes:
    print("[MATCH] Header in wire_boot_header.h EXACTLY matches rdwr_phy62x2 wire header (320 bytes)!")
else:
    print("[MISMATCH] Differences found:")
    for i in range(min(len(hdr_wire), len(header_h_bytes))):
        if hdr_wire[i] != header_h_bytes[i]:
            print(f"  Byte offset {i} (0x{i:03X}): wire=0x{hdr_wire[i]:02X}, header_h=0x{header_h_bytes[i]:02X}")

print("\nDetailed Segments from wire flasher:")
for idx, ihp in enumerate(hp):
    if idx == 0:
        continue
    print(f"  Part {idx-1}: Target/Run Addr = 0x{ihp[0]:08X}, Flash offset = 0x{ihp[2]:08X}, Size = 0x{len(ihp[1]):06X} ({len(ihp[1])} bytes)")
