static inline uint16_t swap16(uint16_t c) {
    return (c >> 8) | (c << 8);
}

// Sample a single pixel (already byte-swapped for SPI) from the 80x160 BMP at 0x1107260C
static inline uint16_t sample_bmp_pixel_swapped(uint8_t x, uint8_t y) {
    if (x >= 80 || y >= 160) return 0;
    const uint8_t *pal = (const uint8_t *)(FACTORY_BMP_WALLPAPER + 54);
    const uint8_t *pix = (const uint8_t *)(FACTORY_BMP_WALLPAPER + 1074);
    uint8_t idx = pix[(159 - y) * 80 + x];
    const uint8_t *pe = pal + ((uint16_t)idx << 2);
    // pe[1] is high byte of RGB565, pe[2] is low byte
    return ((uint16_t)pe[2] << 8) | pe[1];
}

void factory_draw_bmp_wallpaper(void) {
    const uint8_t *pal = (const uint8_t *)(FACTORY_BMP_WALLPAPER + 54);
    const uint8_t *pix = (const uint8_t *)(FACTORY_BMP_WALLPAPER + 1074);
    // Verify 'BM' signature in XIP flash
    const uint8_t *hdr = (const uint8_t *)FACTORY_BMP_WALLPAPER;
    if (hdr[0] != 'B' || hdr[1] != 'M') {
        display_fill_screen(0x0000);
        return;
    }
    uint16_t line_buf[80];
    for (uint8_t y = 0; y < 160; y++) {
        const uint8_t *row = pix + (uint16_t)(159 - y) * 80;
        for (uint8_t x = 0; x < 80; x++) {
            const uint8_t *pe = pal + ((uint16_t)row[x] << 2);
            line_buf[x] = ((uint16_t)pe[2] << 8) | pe[1];
        }
        display_fill_window(0, y, 79, y, line_buf, 80);
    }
}

void factory_draw_sprite_1bpp(uint32_t flash_addr, uint8_t x, uint8_t y, uint16_t fg_color, uint16_t bg_color, bool over_bmp) {
    const uint8_t *sp = (const uint8_t *)flash_addr;
    uint8_t w = sp[0];
    uint8_t h = sp[1];
    if (w == 0 || w > 80 || h == 0 || h > 64) return;
    uint8_t rb = (w + 7) >> 3;
    const uint8_t *data = sp + 10;
    uint16_t fg_sw = swap16(fg_color);
    uint16_t bg_sw = swap16(bg_color);
    uint16_t row_buf[40];
    if (w > 40) w = 40;

    for (uint8_t dy = 0; dy < h; dy++) {
        if (y + dy >= 160) break;
        const uint8_t *rptr = data + dy * rb;
        for (uint8_t dx = 0; dx < w; dx++) {
            uint8_t bit = (rptr[dx >> 3] >> (7 - (dx & 7))) & 1;
            if (bit) {
                row_buf[dx] = fg_sw;
            } else if (over_bmp) {
                row_buf[dx] = sample_bmp_pixel_swapped(x + dx, y + dy);
            } else {
                row_buf[dx] = bg_sw;
            }
        }
        if (x + w <= 80) {
            display_fill_window(x, y + dy, x + w - 1, y + dy, row_buf, w);
        }
    }
}

void factory_draw_big_time(uint8_t hours, uint8_t minutes, uint8_t y, uint16_t fg_color, bool over_bmp) {
    uint8_t digits[5] = {
        (hours / 10) % 10,
        hours % 10,
        10, // ':'
        (minutes / 10) % 10,
        minutes % 10
    };
    const uint8_t x_pos[5] = { 2, 18, 33, 45, 61 };
    for (int i = 0; i < 5; i++) {
        uint32_t addr = FACTORY_SPRITE_BGDIG_BASE + (uint32_t)digits[i] * 68U;
        factory_draw_sprite_1bpp(addr, x_pos[i], y, fg_color, 0x0000, over_bmp);
    }
}

void factory_draw_small_num(uint8_t x, uint8_t y, const char *str, uint16_t fg_color, uint16_t bg_color, bool over_bmp) {
    while (*str && x + 8 <= 80) {
        char c = *str++;
        int idx = -1;
        if (c >= '0' && c <= '9') idx = c - '0';
        else if (c == '/') idx = 10;
        else if (c == ':') idx = 11;
        else if (c == '-') idx = 12;
        if (idx >= 0) {
            factory_draw_sprite_1bpp(FACTORY_SPRITE_SMDIG_BASE + (uint32_t)idx * 20U, x, y, fg_color, bg_color, over_bmp);
        }
        x += 8;
    }
}

static uint8_t draw_factory_glyph(int16_t x, int16_t y, uint16_t cp, uint16_t fg_color, uint16_t bg_color) {
    const uint8_t *g = 0;
    if (cp >= 0x0020 && cp <= 0x007E) {
        uint16_t off = s_asc_offs[cp - 0x0020];
        if (off != 0xFFFF) g = &s_asc_blob[off];
    } else if (cp >= 0x0400 && cp <= 0x045F) {
        uint16_t off = s_cyr_offs[cp - 0x0400];
        if (off != 0xFFFF) g = &s_cyr_blob[off];
    }

    uint16_t fg_sw = swap16(fg_color);
    uint16_t bg_sw = swap16(bg_color);
    uint16_t row_buf[16];

    if (!g) {
        // Space (5x16 blank)
        uint8_t sw = 5;
        if (x >= 0 && x + sw <= 80) {
            for (uint8_t i = 0; i < sw; i++) row_buf[i] = bg_sw;
            for (uint8_t dy = 0; dy < 16; dy++) {
                if (y + dy >= 0 && y + dy < 160) {
                    display_fill_window(x, y + dy, x + sw - 1, y + dy, row_buf, sw);
                }
            }
        }
        return sw;
    }

    uint8_t w = g[0];
    uint8_t h = g[1];
    if (w > 15) w = 15;
    if (h > 16) h = 16;
    const uint8_t *bits = g + 2;

    if (x >= 0 && x + w <= 80) {
        uint16_t bit_idx = 0;
        for (uint8_t dy = 0; dy < h; dy++) {
            for (uint8_t dx = 0; dx < w; dx++) {
                uint8_t b = (bits[bit_idx >> 3] >> (bit_idx & 7)) & 1;
                row_buf[dx] = b ? fg_sw : bg_sw;
                bit_idx++;
            }
            if (y + dy >= 0 && y + dy < 160) {
                display_fill_window(x, y + dy, x + w - 1, y + dy, row_buf, w);
            }
        }
    }
    return w;
}

int16_t factory_draw_utf8(int16_t x, int16_t y, const char *utf8, uint16_t fg_color, uint16_t bg_color) {
    int16_t cur_x = x;
    const uint8_t *p = (const uint8_t *)utf8;
    while (*p) {
        uint16_t cp = 0;
        if (*p < 0x80) {
            cp = *p++;
        } else if ((*p & 0xE0) == 0xC0 && p[1]) {
            cp = ((uint16_t)(p[0] & 0x1F) << 6) | (p[1] & 0x3F);
            p += 2;
        } else if ((*p & 0xF0) == 0xE0 && p[1] && p[2]) {
            cp = ((uint16_t)(p[0] & 0x0F) << 12) | ((uint16_t)(p[1] & 0x3F) << 6) | (p[2] & 0x3F);
            p += 3;
        } else {
            p++;
            continue;
        }
        if (cur_x >= 76) break;
        uint8_t adv = draw_factory_glyph(cur_x, y, cp, fg_color, bg_color);
        cur_x += adv;
    }
    return cur_x - x;
}
